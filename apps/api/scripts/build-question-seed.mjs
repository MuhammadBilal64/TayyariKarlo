const diffs = ['easy', 'medium', 'hard'];

const counts = {};
for (const item of RAW) {
  const key = `${item.topic}|${item.difficulty}`;
  counts[key] = (counts[key] || 0) + 1;
}
for (const topic of topics) {
  for (const d of diffs) {
    const key = `${topic}|${d}`;
    if ((counts[key] || 0) !== 12) {
      throw new Error(`Expected 12 for ${key}, got ${counts[key] || 0}`);
    }
  }
}

const prompts = new Set();
for (const item of RAW) {
  if (prompts.has(item.prompt)) {
    throw new Error(`Duplicate prompt: ${item.prompt}`);
  }
  prompts.add(item.prompt);
}

const balanced = RAW.map((item, index) => balance(item, index));

function esc(s) {
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function emitItem(item) {
  const opts = item.options.map((o) => `'${esc(o)}'`).join(', ');
  const expl = item.explanation ? `,\n    '${esc(item.explanation)}'` : '';
  return `  q(
    '${item.topic}',
    '${item.difficulty}',
    '${esc(item.prompt)}',
    [${opts}],
    ${item.correctIndex}${expl},
  )`;
}

const out = `import type { CreateQuestionInput, Difficulty, Topic } from '@tayyari/shared';

type SeedItem = CreateQuestionInput;

function q(
  topic: Topic,
  difficulty: Difficulty,
  prompt: string,
  options: [string, string, string, string],
  correctIndex: 0 | 1 | 2 | 3,
  explanation?: string,
): SeedItem {
  return { topic, difficulty, prompt, options, correctIndex, explanation };
}

/** Assessment bank: 12 MCQs per topic × difficulty (interview-style). */
export const QUESTION_SEED: SeedItem[] = [
${balanced.map(emitItem).join(',\n')},
];
`;

